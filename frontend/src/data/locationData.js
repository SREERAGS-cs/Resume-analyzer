export function getCitiesForState(stateName) {
    if (!stateName) return [];
    return INDIAN_STATES_AND_CITIES[stateName] || [];
}

/**
 * Normalizes city display string to clean query string
 * e.g. "Bengaluru (Bangalore)" -> "Bengaluru"
 */
export function normalizeCityQuery(cityName) {
    if (!cityName) return "";
    return cityName.split("(")[0].split("/")[0].trim();
}
